# Models sense permisos de Django per decisió pròpia (`default_permissions = ()`) o que no es
# governen per cap bloc. Cap model del projecte pot quedar fora d'aquest fitxer sense
# estar aquí.
EXCLUDED_MODELS = set()


def catalog_models():
    """Tots els models del catàleg: {'app.model': 'nom_main_permission'}."""
    return {
        model: main_permission
        for main_permission, models in MAIN_PERMISSION_MODELS.items()
        for model in models
    }
